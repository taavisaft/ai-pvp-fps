"""blender --background --python tools/uzi/prepare.py
Imports the supplied source without changing it; exports reduced UV meshes and
an editable bolt/casing firing preview to tools/uzi/uzi_animated.blend.
"""
import bpy, math
from pathlib import Path
from mathutils import Matrix, Vector
ROOT=Path(__file__).resolve().parents[2]
bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.fbx(filepath=str(ROOT/'_RESOURCES/uzi/source/uzi_kuszoid.fbx'))
body=next(o for o in bpy.context.scene.objects if o.type=='MESH')
# Canonical game coordinates: +X right, +Y up, +Z forward, in metres.
for v in body.data.vertices:
 x,y,z=v.co;v.co=(y,z,-x+.015)
body.matrix_world=Matrix.Identity(4)
# The coordinate reflection requires reversed faces, including corner UV order.
import bmesh
bm=bmesh.new();bm.from_mesh(body.data);bmesh.ops.reverse_faces(bm,faces=list(bm.faces));bm.to_mesh(body.data);bm.free()
body.name='Uzi - receiver and fixed charging handle'
# Open the existing recessed port through the sidewall. The added bolt lives
# inside the receiver; only its face passes behind this opening.
bpy.ops.mesh.primitive_cube_add(size=1,location=(.022,.0505,-.0045))
cutter=bpy.context.object;cutter.dimensions=(.026,.015,.033)
bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
bpy.context.view_layer.objects.active=body
cut=body.modifiers.new('Ejection port interior','BOOLEAN');cut.operation='DIFFERENCE';cut.object=cutter
bpy.ops.object.modifier_apply(modifier=cut.name);bpy.data.objects.remove(cutter,do_unlink=True)
# A separate internal bolt, full travel 30 mm; charging handle never slides with it.
bpy.ops.mesh.primitive_cube_add(size=1,location=(.008,.050,-.004))
bolt=bpy.context.object;bolt.name='Uzi - internal bolt';bolt.dimensions=(.020,.014,.031)
bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
bevel=bolt.modifiers.new('Bolt edge','BEVEL');bevel.width=.0005;bevel.segments=1
bpy.context.view_layer.objects.active=bolt;bpy.ops.object.modifier_apply(modifier=bevel.name)
# Export positions/normals/UVs. Source textures are sampled by the runtime shader.
def export(ob,ident,ratio,out):
 dup=ob.copy();dup.data=ob.data.copy();bpy.context.scene.collection.objects.link(dup)
 bpy.context.view_layer.objects.active=dup
 if ratio<1:
  m=dup.modifiers.new('Runtime reduction','DECIMATE');m.ratio=ratio
  bpy.ops.object.modifier_apply(modifier=m.name)
 mesh=dup.data;mesh.calc_loop_triangles();uv=mesh.uv_layers.active
 verts=[];indices=[];seen={}
 for tri in mesh.loop_triangles:
  points=[mesh.vertices[k].co for k in tri.vertices]
  face=(points[1]-points[0]).cross(points[2]-points[0])
  if face.length_squared<1e-18:continue
  face.normalize()
  for li in tri.loops:
   loop=mesh.loops[li];p=dup.matrix_world@mesh.vertices[loop.vertex_index].co
   n=mesh.corner_normals[li].vector
   if n.length_squared<.5:n=face
   t=uv.data[li].uv if uv else Vector((0,0))
   key=tuple(round(v,6)for v in (*p,*n,*t))
   if key not in seen:seen[key]=len(verts);verts.append(key)
   indices.append(seen[key])
 out.write(f'inline const float {ident}_VERTS[] = {{\n')
 for v in verts:out.write(','.join(f'{x:.6f}f'for x in v)+',\n')
 out.write(f'}};\ninline const unsigned {ident}_IDX[] = {{\n')
 for i in range(0,len(indices),24):out.write(','.join(map(str,indices[i:i+24]))+',\n')
 out.write('};\n');print('UZI_EXPORT',ident,len(indices)//3,'triangles',flush=True)
 bpy.data.objects.remove(dup,do_unlink=True)
with open(ROOT/'src/imported_uzi_mesh.h','w')as out:
 out.write('// Generated by tools/uzi/prepare.py; source: _RESOURCES/uzi/source/uzi_kuszoid.fbx\n#pragma once\n')
 export(body,'IMPORTED_UZI',.31,out);export(body,'IMPORTED_UZI_LOW',.075,out)
 export(bolt,'IMPORTED_UZI_BOLT',1,out)
# Editable Blender animation uses the same post-shot timing as runtime effects.
rest=bolt.location.copy()
for frame,travel in [(1,-.030),(2,0),(4,-.030),(7,-.030),(8,0),(10,-.030),(13,-.030)]:
 bolt.location=rest+Vector((0,0,travel));bolt.keyframe_insert(data_path='location',frame=frame)
bolt.location=rest
# Restore a full textured material for inspection (Blender Z-up view from game Y-up).
mat=bpy.data.materials.new('Supplied Uzi textures');mat.use_nodes=True
bsdf=mat.node_tree.nodes.get('Principled BSDF')
for name,socket in [('BaseColor','Base Color'),('Roughness','Roughness'),('Metallic','Metallic')]:
 n=mat.node_tree.nodes.new('ShaderNodeTexImage');n.image=bpy.data.images.load(str(ROOT/f'_RESOURCES/uzi/textures/uzi_kuszoid_{name}.png'))
 if name!='BaseColor':n.image.colorspace_settings.name='Non-Color'
 mat.node_tree.links.new(n.outputs['Color'],bsdf.inputs[socket])
body.data.materials.clear();body.data.materials.append(mat)
metal=bpy.data.materials.new('Bolt steel');metal.diffuse_color=(.13,.14,.15,1)
bolt.data.materials.clear();bolt.data.materials.append(metal)
# Two cosmetic spent cases demonstrate delayed ejection in the editable source.
brass=bpy.data.materials.new('Spent brass');brass.diffuse_color=(.55,.33,.08,1)
for shot in (2,8):
 bpy.ops.mesh.primitive_cylinder_add(vertices=12,radius=.0048,depth=.019)
 case=bpy.context.object;case.name=f'Spent casing - shot {shot}';case.data.materials.append(brass)
 for frame in range(1,41):
  t=max(0,(frame-shot-1)/60)
  case.location=Vector((.024+2.1*t,.051+1.1*t-4.905*t*t,-.002-.5*t))
  case.rotation_euler=(t*18,t*11,t*27)
  case.hide_viewport=case.hide_render=frame<=shot+1
  for prop in ('location','rotation_euler','hide_viewport','hide_render'):
   case.keyframe_insert(data_path=prop,frame=frame)
# Present game Y-up source in Blender's Z-up world, after runtime export.
root=bpy.data.objects.new('Game coordinates to Blender view',None)
bpy.context.scene.collection.objects.link(root)
for ob in list(bpy.context.scene.objects):
 if ob!=root:ob.parent=root
root.rotation_euler.x=math.pi/2
from mathutils import Vector
center=Vector((0,-.035,-.025))
bpy.ops.object.camera_add(location=center+Vector((.65,.35,.30)))
cam=bpy.context.object;cam.rotation_euler=(center-cam.location).to_track_quat('-Z','Y').to_euler()
cam.data.type='ORTHO';cam.data.ortho_scale=.60;bpy.context.scene.camera=cam
for offset,power,size in [((.5,-.1,.7),100,.6),((-.4,.3,.25),65,.5)]:
 bpy.ops.object.light_add(type='AREA',location=center+Vector(offset))
 light=bpy.context.object;light.data.energy=power;light.data.size=size
 light.rotation_euler=(center-light.location).to_track_quat('-Z','Y').to_euler()
scene=bpy.context.scene;scene.world=bpy.data.worlds.new('Studio');scene.world.color=(.15,.15,.15)
scene.frame_end=40;scene.render.fps=60;scene.frame_set(1)
scene.render.engine='CYCLES';scene.cycles.samples=16
scene.render.resolution_x=1200;scene.render.resolution_y=800;scene.render.resolution_percentage=100
for image in bpy.data.images:
 if image.filepath:image.filepath=bpy.path.relpath(image.filepath,start=str(ROOT/'tools/uzi'))
bpy.ops.wm.save_as_mainfile(filepath=str(ROOT/'tools/uzi/uzi_animated.blend'))
